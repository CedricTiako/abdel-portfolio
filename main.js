const htmlElement = document.documentElement;

function applyTranslations(lang) {
  const dict = translations[lang];
  if (!dict) return;
  htmlElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });
}

function setLanguage(lang) {
  localStorage.setItem('lang', lang);
  applyTranslations(lang);
}

function initLanguageSwitcher() {
  const stored = localStorage.getItem('lang') || 'fr';
  applyTranslations(stored);
  document.querySelectorAll('[data-lang]').forEach((link) => {
    link.addEventListener('click', (event) => {
      event.preventDefault();
      setLanguage(link.getAttribute('data-lang'));
    });
  });
}

function applyTheme(theme) {
  htmlElement.setAttribute('data-theme', theme);
  localStorage.setItem('theme', theme);
}

function initThemeSwitcher() {
  const storedTheme = localStorage.getItem('theme') || 'dark';
  applyTheme(storedTheme);
  document.querySelectorAll('[data-theme-value]').forEach((item) => {
    item.addEventListener('click', (event) => {
      event.preventDefault();
      applyTheme(item.getAttribute('data-theme-value'));
    });
  });
}

function initFadeIn() {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.2 });

  document.querySelectorAll('.fade-in').forEach((el) => observer.observe(el));
}

function initBackToTop() {
  const btn = document.querySelector('.back-to-top');
  if (!btn) return;
  window.addEventListener('scroll', () => {
    btn.style.display = window.scrollY > 380 ? 'inline-flex' : 'none';
  });
  btn.addEventListener('click', () => window.scrollTo({ top: 0, behavior: 'smooth' }));
}

function init() {
  initLanguageSwitcher();
  initThemeSwitcher();
  initFadeIn();
  initBackToTop();
}

document.addEventListener('DOMContentLoaded', init);
